// Plain data model for assets/data/human_variety.json.
using System.Collections.Generic;
using System.Linq;
using Newtonsoft.Json;

namespace HumanKerbals
{
    public sealed class WeightedTable
    {
        [JsonProperty("Type")] public string Type = "GAMEOBJECT";
        [JsonProperty("WeightedOptionsArray")] public Dictionary<string, int> WeightedOptionsArray = new Dictionary<string, int>();
    }

    /// Settings for converting the game's pre-built kerbal actors (Mission Control rows and big screens,
    /// main-menu vignettes); see ActorPatches.cs. All keys are addressable prefab keys without extension.
    public sealed class ActorSwapData
    {
        [JsonProperty("enabled")] public bool Enabled = true;

        // Stock body kind (substring of the stock mesh name: scientist, jumpsuit, groundcrew, worker, spacesuit)
        // -> human body keys in order of preference; the first one that exists is used.
        [JsonProperty("bodies")] public Dictionary<string, List<string>> Bodies = new Dictionary<string, List<string>>();

        // "m" / "f" -> head and eyes prefab keys; hair lists are picked from per actor.
        [JsonProperty("heads")] public Dictionary<string, string> Heads = new Dictionary<string, string>();
        [JsonProperty("eyes")] public Dictionary<string, string> Eyes = new Dictionary<string, string>();
        [JsonProperty("hair")] public Dictionary<string, List<string>> Hair = new Dictionary<string, List<string>>();

        // Replacement for a stock helmet when the actor wears one (spacesuit actors only).
        [JsonProperty("helmet")] public string Helmet;

        // Stock beards are skinned to the kerbal face, stock glasses sit on the kerbal head.
        [JsonProperty("hideFacialHair")] public bool HideFacialHair = true;
        [JsonProperty("hideGlasses")] public bool HideGlasses;

        public IEnumerable<string> AllKeys()
        {
            foreach (var list in Bodies.Values) foreach (var k in list) yield return k;
            foreach (var k in Heads.Values) yield return k;
            foreach (var k in Eyes.Values) yield return k;
            foreach (var list in Hair.Values) foreach (var k in list) yield return k;
            if (!string.IsNullOrEmpty(Helmet)) yield return Helmet;
        }

        public void Normalize()
        {
            Bodies = new Dictionary<string, List<string>>(Bodies, System.StringComparer.OrdinalIgnoreCase);
            Heads = new Dictionary<string, string>(Heads, System.StringComparer.OrdinalIgnoreCase);
            Eyes = new Dictionary<string, string>(Eyes, System.StringComparer.OrdinalIgnoreCase);
            Hair = new Dictionary<string, List<string>>(Hair, System.StringComparer.OrdinalIgnoreCase);
        }

        /// Drops every key whose prefab does not exist (so partially built asset sets fall back gracefully).
        public void Prune(System.Func<string, bool> exists, System.Action<string> warn)
        {
            foreach (var kind in Bodies.Keys.ToList())
            {
                var missing = Bodies[kind].Where(k => !exists(k)).ToList();
                if (missing.Count > 0) warn($"actorSwap.bodies.{kind}: missing {string.Join(", ", missing)}");
                Bodies[kind] = Bodies[kind].Except(missing).ToList();
            }
            foreach (var tag in Heads.Keys.ToList())
            {
                if (exists(Heads[tag])) continue;
                warn($"actorSwap.heads.{tag}: missing {Heads[tag]}");
                Heads.Remove(tag);
            }
            foreach (var tag in Eyes.Keys.ToList())
            {
                if (exists(Eyes[tag])) continue;
                warn($"actorSwap.eyes.{tag}: missing {Eyes[tag]}");
                Eyes.Remove(tag);
            }
            foreach (var tag in Hair.Keys.ToList())
            {
                var missing = Hair[tag].Where(k => !exists(k)).ToList();
                if (missing.Count > 0) warn($"actorSwap.hair.{tag}: missing {string.Join(", ", missing)}");
                Hair[tag] = Hair[tag].Except(missing).ToList();
            }
            if (!string.IsNullOrEmpty(Helmet) && !exists(Helmet))
            {
                warn($"actorSwap.helmet: missing {Helmet}");
                Helmet = null;
            }
        }
    }

    /// Rule that renames every stock kerbal sound event to the mod's counterpart: an event whose name
    /// contains `from` plays through the event with the same name and `to` instead, when a bank in
    /// assets/soundbanks defines it (see AudioRemapPatches.cs).
    public sealed class AudioWordSwap
    {
        [JsonProperty("enabled")] public bool Enabled = true;
        [JsonProperty("from")] public string From = "Kerbal";
        [JsonProperty("to")] public string To = "Gerbal";
    }

    /// One entry of assets/data/narration_remap.json (generated by tools/vo_gerbal.py): a stock
    /// voice-over event whose line says "Kerbal", and the mod event that plays the "Gerbal" version.
    public sealed class NarrationLine
    {
        [JsonProperty("event")] public string Event;
        [JsonProperty("eventId")] public uint EventId;
        [JsonProperty("stockEventId")] public uint StockEventId;
        [JsonProperty("stockSourceId")] public uint StockSourceId;
        [JsonProperty("samples")] public long Samples;
        [JsonProperty("rate")] public int Rate;
        [JsonProperty("words")] public int Words;
        [JsonProperty("text")] public string Text;

        public float Seconds => Rate > 0 ? Samples / (float)Rate : 0f;
    }

    public sealed class NarrationRemap
    {
        [JsonProperty("bank")] public string Bank;
        [JsonProperty("bankId")] public uint BankId;
        [JsonProperty("lines")] public List<NarrationLine> Lines = new List<NarrationLine>();
    }

    public sealed class HumanVarietyData
    {
        // Category name (BODY, HEAD, EYES, HAIR, HELMET, ...) -> list of addressable prefab keys (upper case, no extension).
        [JsonProperty("gameObjectCategories")] public Dictionary<string, List<string>> GameObjectCategories = new Dictionary<string, List<string>>();

        // Weighted table name (e.g. SKINCOLOR_OPTIONS_WEIGHTED) -> table.
        [JsonProperty("weightedOptions")] public Dictionary<string, WeightedTable> WeightedOptions = new Dictionary<string, WeightedTable>();

        // String category name (e.g. ENGLISH_N_KERBALNAMES) -> names.
        [JsonProperty("stringCategories")] public Dictionary<string, List<string>> StringCategories = new Dictionary<string, List<string>>();

        // Surnames used instead of "Kerman". Empty list keeps the stock surname generator.
        [JsonProperty("surnames")] public List<string> Surnames = new List<string>();

        // Predefined (hero/dev) kerbal key -> attribute overrides applied on top of the stock JSON.
        [JsonProperty("predefinedOverrides")] public Dictionary<string, Dictionary<string, object>> PredefinedOverrides = new Dictionary<string, Dictionary<string, object>>();

        // Word rule for sound event names (Kerbal -> Gerbal), see AudioRemapPatches.cs.
        [JsonProperty("audioWordSwap")] public AudioWordSwap AudioWordSwap = new AudioWordSwap();

        // Stock event names that contain the word. The id-based PostEvent overloads only carry hashes,
        // so the rule needs the names to pre-compute the id table; unlisted names still work on the
        // string overloads.
        [JsonProperty("stockAudioEvents")] public List<string> StockAudioEvents = new List<string>();

        // Explicit exceptions: stock Wwise event name -> mod Wwise event name.
        [JsonProperty("audioRemap")] public Dictionary<string, string> AudioRemap = new Dictionary<string, string>();

        // Stock appearance key -> human key, applied to kerbals that already exist in a save (their
        // attributes were generated before the mod was installed). Keys compare case-insensitively.
        [JsonProperty("legacyRemap")] public Dictionary<string, string> LegacyRemap = new Dictionary<string, string>();

        // Conversion of the pre-built menu-room actors (see ActorPatches.cs).
        [JsonProperty("actorSwap")] public ActorSwapData ActorSwap = new ActorSwapData();

        public void BuildLookups()
        {
            ActorSwap = ActorSwap ?? new ActorSwapData();
            ActorSwap.Normalize();
            AudioWordSwap = AudioWordSwap ?? new AudioWordSwap();
            StockAudioEvents = StockAudioEvents ?? new List<string>();
            // Strip the "_comment" pseudo-entries the JSON file uses for documentation.
            GameObjectCategories.Remove("_comment");
            WeightedOptions.Remove("_comment");
            StringCategories.Remove("_comment");
            PredefinedOverrides.Remove("_comment");
            AudioRemap.Remove("_comment");
            LegacyRemap.Remove("_comment");
            LegacyRemap = new Dictionary<string, string>(LegacyRemap, System.StringComparer.OrdinalIgnoreCase);
        }
    }
}
